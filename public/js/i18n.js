// Languages listed in LANGUAGES but not (yet) in TRANSLATIONS fall back to English.
const FALLBACK_LANG = "en";
const STORAGE_KEY = "trividha_lang";
const COOKIE_KEY = "trividha_lang";
const COOKIE_MAX_AGE_DAYS = 400; // ~13 months — longest a browser will honor anyway

// A plain (non-httpOnly) cookie mirror of localStorage. localStorage alone
// already survives a server restart (it's a browser feature, not a server
// one) but it's wiped by "clear site data", a private window, or a browser
// switch — the cookie is the belt-and-braces copy so a returning visitor
// keeps their picked language either way.
function readCookie(name) {
  const match = document.cookie.match(new RegExp("(?:^|; )" + name + "=([^;]*)"));
  return match ? decodeURIComponent(match[1]) : null;
}

function writeCookie(name, value, days) {
  const expires = new Date(Date.now() + days * 24 * 60 * 60 * 1000).toUTCString();
  document.cookie = `${name}=${encodeURIComponent(value)}; expires=${expires}; path=/; SameSite=Lax`;
}

function getTranslation(langCode, key) {
  const table = TRANSLATIONS[langCode] || {};
  const fallback = TRANSLATIONS[FALLBACK_LANG] || {};
  return table[key] ?? fallback[key] ?? key;
}

function getCurrentLanguage() {
  let stored = null;
  try {
    stored = localStorage.getItem(STORAGE_KEY);
  } catch (e) {
    /* localStorage unavailable (private mode etc.) — fall through to the cookie */
  }
  if (!stored) {
    stored = readCookie(COOKIE_KEY);
  }
  if (stored && LANGUAGES.some((l) => l.code === stored)) return stored;
  return FALLBACK_LANG;
}

// Has this visitor ever picked a language before (localStorage or cookie)?
// Used to decide whether "/" should skip straight to /home.
function hasStoredLanguage() {
  let stored = null;
  try {
    stored = localStorage.getItem(STORAGE_KEY);
  } catch (e) {
    /* ignore */
  }
  if (!stored) stored = readCookie(COOKIE_KEY);
  return Boolean(stored && LANGUAGES.some((l) => l.code === stored));
}

function setCurrentLanguage(langCode) {
  try {
    localStorage.setItem(STORAGE_KEY, langCode);
  } catch (e) {
    /* ignore — falls back to the cookie below */
  }
  writeCookie(COOKIE_KEY, langCode, COOKIE_MAX_AGE_DAYS);
}

// Applies langCode to every translatable node in the document, sets dir/lang
// on <html>, and updates anything else (clock format hook, etc.) callers ask for.
function applyLanguage(langCode) {
  const meta = LANGUAGES.find((l) => l.code === langCode) || LANGUAGES.find((l) => l.code === FALLBACK_LANG);
  document.documentElement.lang = meta.code;
  document.documentElement.dir = RTL_LANGS.has(meta.code) ? "rtl" : "ltr";

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    el.textContent = getTranslation(langCode, el.getAttribute("data-i18n"));
  });
  document.querySelectorAll("[data-i18n-attr]").forEach((el) => {
    // format: data-i18n-attr="placeholder:some.key|title:other.key"
    el.getAttribute("data-i18n-attr")
      .split("|")
      .forEach((pair) => {
        const [attr, key] = pair.split(":");
        if (attr && key) el.setAttribute(attr, getTranslation(langCode, key));
      });
  });

  document.querySelectorAll("[data-lang-pill]").forEach((el) => {
    el.textContent = getTranslation(langCode, "lang_pill");
  });

  setCurrentLanguage(langCode);
}
